import { Template } from '../types';

export const customSketchTemplate: Template = {
  id: 'custom-sketch',
  name: 'Custom Sketch',
  description: 'A fully custom p5.js sketch generated by AI. Write raw p5 code!',
  supportsLiveParams: true,
  params: [
    {
      id: 'code',
      name: 'p5.js Code',
      type: 'code',
      default: `function setup() {
  createCanvas(windowWidth, windowHeight);
  background(20);
}

function draw() {
  fill(255, 100);
  noStroke();
  circle(mouseX, mouseY, 50);
}

function windowResized() {
  resizeCanvas(windowWidth, windowHeight);
  background(20);
}`
    }
  ],
  generateCode: (params, seed) => {
    const values = Object.fromEntries(Object.entries(params).filter(([id]) => id !== 'code'));
    // p5's global-mode functions (randomSeed, noiseSeed) aren't bound to window
    // until p5 bootstraps, which happens right before it calls setup(). Calling
    // them at the top level of the script (before that bootstrap) throws
    // "randomSeed is not defined". Defer the seeding by wrapping setup()
    // instead, so it runs once p5 has attached its globals.
    return `
var params = ${JSON.stringify(values)};
window.addEventListener('message', function(event) {
  if (event.source === window.parent && event.data?.type === 'params-update') {
    Object.keys(params).forEach(function(id) {
      if (Object.prototype.hasOwnProperty.call(event.data.params, id)) params[id] = event.data.params[id];
    });
  }
});

${params.code}

(function() {
  var __seed = ${seed};
  var __originalSetup = (typeof setup === 'function') ? setup : null;
  window.setup = function() {
    if (typeof randomSeed === 'function') randomSeed(__seed);
    if (typeof noiseSeed === 'function') noiseSeed(__seed);
    if (__originalSetup) __originalSetup();
  };
})();
    `;
  }
};
